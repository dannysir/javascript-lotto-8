import { runWithInput } from '../test-helpers/testUtils.js';

describe('로또 테스트', () => {
  beforeEach(() => {
    jest.restoreAllMocks();
  });

  test('기능 테스트', async () => {
    const randoms = [
      [8, 21, 23, 41, 42, 43],
      [3, 5, 11, 16, 32, 38],
      [7, 11, 16, 35, 36, 44],
      [1, 8, 11, 31, 41, 42],
      [13, 14, 16, 38, 42, 45],
      [7, 11, 30, 40, 42, 43],
      [2, 13, 22, 32, 38, 45],
      [1, 3, 5, 14, 22, 45],
    ];
    const inputs = ['8000', '1,2,3,4,5,6', '7'];

    const logSpy = await runWithInput(inputs, randoms);

    const logs = [
      '8개를 구매했습니다.',
      '[8, 21, 23, 41, 42, 43]',
      '[3, 5, 11, 16, 32, 38]',
      '[7, 11, 16, 35, 36, 44]',
      '[1, 8, 11, 31, 41, 42]',
      '[13, 14, 16, 38, 42, 45]',
      '[7, 11, 30, 40, 42, 43]',
      '[2, 13, 22, 32, 38, 45]',
      '[1, 3, 5, 14, 22, 45]',
      '3개 일치 (5,000원) - 1개',
      '4개 일치 (50,000원) - 0개',
      '5개 일치 (1,500,000원) - 0개',
      '5개 일치, 보너스 볼 일치 (30,000,000원) - 0개',
      '6개 일치 (2,000,000,000원) - 0개',
      '총 수익률은 62.5%입니다.',
    ];

    logs.forEach((log) => {
      expect(logSpy).toHaveBeenCalledWith(expect.stringContaining(log));
    });
  });


  describe('예외 테스트', () => {
    test.each([
      ['1001', '6000', '1,2,3,4,5,6', '45'],
      ['1', '6000', '1,2,3,4,5,6', '45'],
      ['6000', '-1,2,3,4,5,6', '1,2,3,4,5,6', '45'],
      ['6000', '1,2,3,4,5,60', '1,2,3,4,5,6', '45'],
      ['6000', '1,2,,4,5,6', '1,2,3,4,5,6', '45'],
      ['6000', '1,2,십일,4,5,6', '1,2,3,4,5,6', '45'],
      ['6000', '1,2,3,4,5,6', '-1', '45'],
      ['6000', '1,2,3,4,5,6', '일', '45'],
      ['6000', '1,2,3,4,5,6', '100', '45'],
    ])('[입력 예외] - 금액 : %s, 로또 번호 : %s, 보너스 번호 : %s', async (...inputs) => {
      const randoms = [
        [8, 21, 23, 41, 42, 43],
        [3, 5, 11, 16, 32, 38],
        [7, 11, 16, 35, 36, 44],
        [1, 8, 11, 31, 41, 42],
        [13, 14, 16, 38, 42, 45],
        [7, 11, 30, 40, 42, 43],
        [2, 13, 22, 32, 38, 45],
        [1, 3, 5, 14, 22, 45],
      ];

      const logSpy = await runWithInput(inputs, randoms);

      expect(logSpy).toHaveBeenCalledWith(expect.stringContaining('[ERROR]'));
    });
  });
});
